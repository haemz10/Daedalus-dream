  DD.LANG_TAGS = { en: 'en', ko: 'ko', ja: 'ja', fr: 'fr', es: 'es', zh: 'zh-Hans' };

  var current = 'en';
  DD.setLang = function (code) {
    current = DD.I18N[code] ? code : 'en';
    return current;
  };
  DD.getLang = function () { return current; };
  DD.t = function (key, params) {
    var s = DD.I18N[current][key];
    if (s == null) s = en[key];
    if (s == null) return key;
    if (params) {
      s = s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] != null ? String(params[k]) : m; });
    }
    return s;
  };
